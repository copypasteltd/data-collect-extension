  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const appRoot = path.join(root, "app");
  const manifest = { manifest_version: 3, version: "0.3.0", background: { service_worker: "background.js", type: "module" }, side_panel: { default_path: "sidepanel.html" }, icons: Object.fromEntries([16, 32, 48, 128].map((size) => [size, "icons/icon-" + size + ".png"])) };
  put(appRoot, "package.json", { name: "synthetic", version: "0.3.0", type: "module" });
  put(appRoot, "package-lock.json", { version: "0.3.0", lockfileVersion: 3 });
  put(appRoot, "public/manifest.json", manifest);
  put(appRoot, "dist/manifest.json", manifest);
  put(appRoot, "dist/background.js", "export const synthetic = true;");
  put(appRoot, "dist/content.js", "(() => {})();");
  put(appRoot, "dist/sidepanel.html", '<script type="module" src="./assets/sidepanel-fake.js"></script>');
  put(appRoot, "dist/assets/sidepanel-fake.js", "console.log('synthetic');");
  put(appRoot, "dist/assets/sidepanel-fake.css", "body { color: black; }");
