function copiedCli(appRoot) {
  const script = path.join(appRoot, "scripts/package-release.mjs");
  fs.mkdirSync(path.dirname(script), { recursive: true });
  fs.copyFileSync(path.join(app, "scripts/package-release.mjs"), script);
  return script;
}

test("portable archive names reject traversal, credentials and Windows aliases", () => {
  for (const name of ["../x", "/x", "a/../x", "a//x", "./x", "a\\x", "C:/x", "a:b", ".env", "a/.env.local", "a/CON.txt", "a/x.", "a/x ", "a/%2e%2e/x", "profile/x", "node_modules/x", "credentials.json", "test-profile-x/x", "a/x.pem", "recordings/x", "a\0x"]) {
    assert.throws(() => validateArchivePath(name), /Unsafe/);
  }
  for (const name of ["manifest.json", "assets/sidepanel-a_B9.js", "extension-logic-clone/SKILL.md", "docs/交付/2026-11-13/native-release/VERIFICATION.json"]) assert.equal(validateArchivePath(name), name);
});

test("ZIP roundtrips generated byte cases, sorts paths and ignores input order", () => {
  for (let n = 1; n <= 40; n++) {
    const bytes = Uint8Array.from({ length: n * 31 }, (_, i) => (n * 13 + i * 41) % 256);
    const entries = [{ path: "b/code.js", bytes }, { path: "a/SKILL.md", bytes: Buffer.from("synthetic-" + n) }];
    const zip = createArchive(entries);
    assert.deepEqual(zip, createArchive([...entries].reverse()));
    const decoded = unzipSync(zip);
    assert.deepEqual(Object.keys(decoded), ["a/SKILL.md", "b/code.js"]);
    for (const entry of entries) assert.deepEqual(decoded[entry.path], new Uint8Array(entry.bytes));
  }
  assert.throws(() => createArchive([{ path: "a.js", bytes: Buffer.from("x") }, { path: "A.js", bytes: Buffer.from("y") }]), /colliding/);
  assert.throws(() => createArchive([{ path: "a.js", bytes: Buffer.alloc(16 * 1024 * 1024 + 1) }]), /size/);
});

test("release includes only two runtime ZIPs plus checksums and a truthful byte manifest", (t) => {
  const { appRoot, root } = fixture(t);
  const inputs = collectReleaseInputs({ appRoot, verificationReport: reportPath });
  const result = createReleaseArtifacts(inputs);
  assert.deepEqual(result.files.map((file) => file.path), ["logic-recorder-chrome-v0.3.0.zip", "extension-logic-clone-v0.3.0.zip", "SHA256SUMS.txt", "release-manifest.json"]);
  const files = new Map(result.files.map((file) => [file.path, file.bytes]));
  for (const artifact of result.manifest.artifacts) {
    assert.equal(artifact.sha256, digest(files.get(artifact.path)));
    assert.equal(artifact.size, files.get(artifact.path).byteLength);
    const entries = unzipSync(files.get(artifact.path));
    assert.deepEqual(Object.keys(entries).sort(), artifact.entries.map((entry) => entry.path).sort());
    for (const entry of artifact.entries) {
      assert.equal(entry.sha256, digest(entries[entry.path]));
      assert.equal(entry.size, entries[entry.path].byteLength);
    }
  }
  const sums = Buffer.from(files.get("SHA256SUMS.txt")).toString("utf8").trim().split("\n");
  for (const sum of sums) { const [hash, name] = sum.split("  "); assert.equal(hash, digest(files.get(name))); }
  const encoded = Buffer.from(files.get("release-manifest.json")).toString("utf8");
  assert.equal(encoded.includes(root), false);
  assert.equal(encoded.includes("synthetic-not-full-acceptance"), false);
  assert.deepEqual(result.manifest.provenance.verificationReport, { size: fs.statSync(path.join(root, reportPath)).size, sha256: digest(fs.readFileSync(path.join(root, reportPath))) });
  assert.equal(result.manifest.provenance.sourceInputHash, digest(Buffer.from(JSON.stringify(result.manifest.provenance.sourceInputs, null, 2) + "\n")));
});

test("fixed roots exclude profiles, dependencies, credentials, environment and old reports", (t) => {
  const { root, appRoot } = fixture(t);
  for (const file of ["dist/.env", "dist/profile/Cookies", "dist/node_modules/token.js", "skills/extension-logic-clone/.env.local", "skills/extension-logic-clone/tests/sample.py", "skills/extension-logic-clone/credentials.json", "skills/extension-logic-clone/scripts/__pycache__/a.pyc"]) put(appRoot, file, "FAKE-DO-NOT-SHIP");
  put(appRoot, "test-profile-old/Cookies", "FAKE-DO-NOT-SHIP");
  put(root, "docs/交付/2026-11-13/old-report.json", "FAKE-DO-NOT-SHIP");
  const result = createReleaseArtifacts(collectReleaseInputs({ appRoot }));
  assert.equal(JSON.stringify(result.manifest).includes("FAKE-DO-NOT-SHIP"), false);
  for (const zip of result.files.filter((file) => file.path.endsWith(".zip"))) {
    for (const [name, bytes] of Object.entries(unzipSync(zip.bytes))) {
      validateArchivePath(name);
      assert.equal(Buffer.from(bytes).toString().includes("FAKE-DO-NOT-SHIP"), false);
    }
  }
  put(appRoot, "dist/unexpected.txt", "Unexpected ordinary file.");
  assert.throws(() => collectReleaseInputs({ appRoot }), /Unexpected file/);
});

test("version mismatch, missing entry/icon and unbound source inputs fail closed", (t) => {
  const { appRoot, manifest } = fixture(t);
  put(appRoot, "dist/manifest.json", { ...manifest, version: "0.2.0" });
  assert.throws(() => packageRelease({ appRoot }), /dist manifest version/);
  assert.equal(fs.existsSync(path.join(appRoot, "release")), false);
  put(appRoot, "dist/manifest.json", manifest);
  put(appRoot, "public/manifest.json", { ...manifest, version: "0.2.0" });
  assert.throws(() => collectReleaseInputs({ appRoot }), /public manifest version/);
  put(appRoot, "public/manifest.json", manifest);
  const inputs = collectReleaseInputs({ appRoot });
  for (const missing of ["content.js", "background.js", "sidepanel.html", "icons/icon-128.png"]) assert.throws(() => createReleaseArtifacts({ ...inputs, extensionFiles: inputs.extensionFiles.filter((entry) => entry.path !== missing) }), /Missing required/);
  assert.throws(() => createReleaseArtifacts({ ...inputs, sourceFiles: [{ path: "app/package.json", bytes: Buffer.from("unrelated") }] }), /provenance/);
  assert.throws(() => createReleaseArtifacts({ ...inputs, version: "../oops" }), /version/);
});

test("symlink/junction input and linked output root are rejected", (t) => {
  const { root, appRoot } = fixture(t);
  const target = path.join(root, "linked-target");
  fs.mkdirSync(target);
  const link = path.join(appRoot, "dist", "linked-folder");
  fs.symlinkSync(target, link, process.platform === "win32" ? "junction" : "dir");
  assert.throws(() => collectReleaseInputs({ appRoot }), /Symlink/);
  fs.rmSync(link);
  fs.symlinkSync(target, path.join(appRoot, "release"), process.platform === "win32" ? "junction" : "dir");
  assert.throws(() => packageRelease({ appRoot }), /Symlink/);
  assert.deepEqual(fs.readdirSync(target), []);
});

test("opt-in docs are separate files; reports cannot escape current native docs", (t) => {
  const { appRoot } = fixture(t);
  const result = packageRelease({ appRoot, includeInstallDoc: true, releaseNotes: true, verificationReport: reportPath });
  assert.deepEqual(result.manifest.documents.map((entry) => entry.path), ["INSTALL.md", "RELEASE-NOTES.md"]);
  assert.equal(fs.existsSync(path.join(appRoot, "release/v0.3.0/INSTALL.md")), true);
  for (const file of result.files.filter((entry) => entry.path.endsWith(".zip"))) {
    assert.equal(Object.keys(unzipSync(file.bytes)).some((name) => /INSTALL.md|RELEASE-NOTES.md|VERIFICATION.json/.test(name)), false);
  }
  for (const verificationReport of ["../report.json", "docs/交付/2026-11-13/old.json", "E:/report.json", ".env"]) assert.throws(() => collectReleaseInputs({ appRoot, verificationReport }));
  const before = fs.readFileSync(path.join(appRoot, "release/v0.3.0/release-manifest.json"));
  assert.throws(() => packageRelease({ appRoot }), { code: "EEXIST" });
  assert.deepEqual(fs.readFileSync(path.join(appRoot, "release/v0.3.0/release-manifest.json")), before);
});

test("import and help do not pack; actual CLI packages a synthetic project only", (t) => {
  const { appRoot } = fixture(t);
  const script = copiedCli(appRoot);
  const imported = spawnSync(process.execPath, ["--input-type=module", "-e", "await import(" + JSON.stringify(pathToFileURL(script).href) + ")"], { cwd: appRoot, encoding: "utf8" });
  assert.equal(imported.status, 0, imported.stderr);
  assert.equal(fs.existsSync(path.join(appRoot, "release")), false);
  const help = spawnSync(process.execPath, [script, "--help"], { cwd: appRoot, encoding: "utf8" });
  assert.equal(help.status, 0, help.stderr);
  assert.equal(fs.existsSync(path.join(appRoot, "release")), false);
  const bad = spawnSync(process.execPath, [script, "--verification-report"], { cwd: appRoot, encoding: "utf8" });
  assert.equal(bad.status, 1);
  assert.equal(fs.existsSync(path.join(appRoot, "release")), false);
  const result = spawnSync(process.execPath, [script, "--verification-report", reportPath], { cwd: appRoot, encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr);
  const summary = JSON.parse(result.stdout);
  assert.equal(summary.output, "app/release/v0.3.0");
  assert.equal(summary.files.length, 4);
  assert.equal(result.stdout.includes(appRoot), false);
});
